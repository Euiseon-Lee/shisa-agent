import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {Store} from './store.ts';
import {sourceMetadata} from './todo-source-meta.ts';
import {mailImapConn} from './connectors.ts';
import {connectMail} from './mail-connect.ts';
import {writeMailState,writeAccountItems} from './mail-sync.ts';
test('metadata resolves exact origin and refuses ambiguous or missing mail accounts',()=>{
 const s=new Store(':memory:');const accounts=[{id:'work',preset:'gmail',user:'work@example.com',password:'test',purpose:'work'},{id:'home',preset:'gmail',user:'home@example.com',password:'test',purpose:'personal'}];
 const cfg={connectors:{mail:mailImapConn({accounts},{})}} as any;
 writeMailState(s,{phase:'ok',accounts:accounts.map(a=>({...a,phase:'ok'}))} as any);
 const msg={messageId:'one',uid:1,date:'2026-11-19',subject:'x',from:'sender'};
 writeAccountItems(s,'work',[{...msg,account:'work@example.com'}] as any);
 s.upsertNode('session:1','session','x',{tool:'codex'});
 let meta=sourceMetadata(s,cfg);
 assert.deepEqual(meta({id:'session:1',source:'session'}),{sourceTool:'codex'});
 assert.deepEqual(meta({id:'session:missing',source:'session'}),{});
 assert.deepEqual(meta({id:'mail:one',source:'mail'}),{mailPurpose:'work'});
 assert.deepEqual(meta({id:'mail:missing',source:'mail'}),{});
 assert.deepEqual(meta({id:'mail:legacy',source:'mail',origin:{kind:'mail',ref:'mail:legacy',purpose:'work'}}),{mailPurpose:'work'});
 writeAccountItems(s,'home',[{...msg,account:'home@example.com'}] as any);
 assert.deepEqual(sourceMetadata(s,cfg)({id:'mail:one',source:'mail'}),{});
 s.db.close();
});
test('purpose-only update is local, keeps credentials and supports clearing purpose',async()=>{
 const path=join(mkdtempSync(join(tmpdir(),'shisa-purpose-')),'config.json');
 const value={mode:'imap',accounts:[{id:'one',preset:'gmail',user:'one@example.com',password:'keep-secret'}]};
 writeFileSync(path,JSON.stringify({connectors:{mail:value},unrelated:true}));
 let current=mailImapConn(value,{}),applied=0;
 const deps={path,env:{},current:()=>current,apply:()=>{throw Error('must not fetch or replace cached mail')},fetch:async()=>{throw Error('must not contact mail server')},applyPurpose:(c:any)=>{current=c;applied++;}};
 const result=await connectMail({id:'one',purpose:'work'},deps);
 assert.equal(result.ok,true);assert.equal(applied,1);
 const saved=JSON.parse(readFileSync(path,'utf8'));assert.equal(saved.unrelated,true);assert.equal(saved.connectors.mail.accounts[0].password,'keep-secret');assert.equal(saved.connectors.mail.accounts[0].purpose,'work');
 assert.equal((await connectMail({id:'one',purpose:'invalid'},deps)).ok,false);
 assert.equal((await connectMail({id:'one',purpose:''},deps)).ok,true);
 assert.equal(JSON.parse(readFileSync(path,'utf8')).connectors.mail.accounts[0].purpose,undefined);
});
