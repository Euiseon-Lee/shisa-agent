import {test} from 'node:test';
import assert from 'node:assert/strict';
import {loadPage,fakeCy} from './fake-dom.js';
import {localDay} from '../src/todos.js';
const timer=setInterval;globalThis.setInterval=(...args)=>{const h=timer(...args);h.unref();return h;};
test('recurring rows have metadata and no checkbox; completion list caps after ten',async()=>{
 const today=localDay(),t={id:'t',title:'Routine',source:'user',priority:2,seriesId:'s',scheduledDate:today,schedule:{mode:'repeat',start:today,end:'9999-12-31',days:[0,1,2,3,4,5,6]}};
 const raw={generatedAt:new Date().toISOString(),todos:[t,...Array.from({length:11},(_,i)=>({id:'u'+i,title:'Undated '+i,source:'user',priority:2}))],recurring:Array.from({length:6},(_,i)=>({...t,id:'r'+i,seriesId:'s'+i,canEdit:true,canStop:true})),recentDone:Array.from({length:11},(_,i)=>({id:'d'+i,title:'Done '+i,doneAt:new Date().toISOString(),priority:2,source:'user'})),projects:[],today:{date:today,items:[]}};
 const cy=fakeCy({getLang:'ko',getDashboard:()=>({ok:true,data:raw}),getCharacter:'shisa'});
 const page=await loadPage('panel',{cy});await page.settle();page.click('#nav button[data-section="todos"]');await page.settle();
 assert.ok(page.$('.recurring-list.is-scrollable'));assert.equal(page.$('.recurring-list').children.length,6);
 const row=page.$('.recurring-row');assert.ok(row);assert.equal(row.querySelector('input'),null);assert.equal(row.querySelector('.recurring-summary').textContent,'매일');
 assert.ok(page.$('.bucket-today input[type="checkbox"]'));assert.equal(page.$('.bucket-today .recurring-icon'),null);
 assert.ok(page.$('.undated-list.is-scrollable'));assert.equal(page.$('.undated-list').children.length,11);
 assert.equal(page.$('.bucket-today .is-scrollable'),null);
 assert.equal(page.$('.recent-completed-list'),null);
 assert.equal(page.$('.group.done .schedule-head').getAttribute('aria-expanded'),'false');
 page.click(page.$('.group.done .schedule-head'));
 assert.ok(page.$('.recent-completed-list.is-scrollable'));assert.equal(page.$('.recent-completed-list').children.length,11);
 const completedHead=()=>page.$('.group.done .schedule-head');
 assert.ok(completedHead().querySelector('.caret'));
 assert.equal(completedHead().getAttribute('aria-expanded'),'true');
 page.click(completedHead());assert.equal(page.$('.recent-completed-list'),null);
 assert.equal(completedHead().getAttribute('aria-expanded'),'false');
 completedHead().dispatchEvent(new page.document.defaultView.KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
 assert.equal(page.$('.recent-completed-list').children.length,11);
 completedHead().dispatchEvent(new page.document.defaultView.KeyboardEvent('keydown',{key:' ',bubbles:true}));
 assert.equal(page.$('.recent-completed-list'),null);
 page.click(completedHead());assert.ok(page.$('.recent-completed-list.is-scrollable'));
 assert.equal(page.errors.length,0);
});
